def optimization_discovery_agent_node(state: OptimizationAgentState) -> Dict[str, Any]:
    """
    Agent 1 (Stage 11): OptimizationDiscoveryAgent
    Role: Autonomous Multi-Dimensional Optimization Discovery Architect
    System Prompt: Defined in AGENT_DEFINITIONS["optimization_discovery_agent"]
    """
    track = _init_tracking(state)
    key_mgr = get_default_key_manager()
    engine = OptimizationDiscoveryEngine(key_manager=key_mgr)

    discovery_result = engine.discover_all_dimensions(state)
    track["stage_status"]["optimization_discovery_agent"] = "completed"
    return {
        **track,
        "optimization_candidates": discovery_result["optimization_candidates"],
        "dimension_analyses": discovery_result["dimension_analyses"],
        "key_usage_log": key_mgr.get_usage_log(),
    }


def tradeoff_assessment_agent_node(state: OptimizationAgentState) -> Dict[str, Any]:
    """
    Agent 2 (Stage 12): TradeoffAssessmentAgent
    Role: Feasibility, Implementation Risk, and Benefit Trade-Off Evaluator
    System Prompt: Defined in AGENT_DEFINITIONS["tradeoff_assessment_agent"]
    """
    track = _init_tracking(state)
    key_mgr = get_default_key_manager()
    evaluator = TradeoffEvaluator(key_manager=key_mgr)

    candidates = state.get("optimization_candidates", [])
    eval_result = evaluator.evaluate_candidates(candidates)

    track["stage_status"]["tradeoff_assessment_agent"] = "completed"
    return {
        **track,
        "tradeoff_assessments": eval_result.get("tradeoff_assessments", []),
        "tier_classifications": eval_result.get("tier_classifications", {}),
    }


def report_generation_agent_node(state: OptimizationAgentState) -> Dict[str, Any]:
    """
    Agent 3 (Stage 13): ReportGenerationAgent
    Role: Structured Audit Report and Executive Summary Synthesizer
    System Prompt: Defined in AGENT_DEFINITIONS["report_generation_agent"]
    """
    track = _init_tracking(state)
    wf_id = state.get("workflow_id", "workflow")
    key_mgr = get_default_key_manager()
    _, _, masked_key = key_mgr.get_key_for_task("report_generation")

    json_report = generate_json_report(state, masked_key)
    md_report = generate_markdown_report(state, masked_key)

    reports_dir = _resolve_reports_dir()
    json_path = reports_dir / f"{wf_id}_optimization_report.json"
    md_path = reports_dir / f"{wf_id}_optimization_report.md"

    json_path.write_text(json.dumps(json_report, indent=2), encoding="utf-8")
    md_path.write_text(md_report, encoding="utf-8")

    track["stage_status"]["report_generation_agent"] = "completed"
    return {
        **track,
        "final_report": json_report,
        "final_markdown_report": md_report,
    }


