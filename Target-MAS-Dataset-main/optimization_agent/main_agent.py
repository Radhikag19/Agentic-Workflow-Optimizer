def stage_9_comparison_tool_node(state: OptimizationAgentState) -> Dict[str, Any]:
    """Stage 9 Tool Call: compare_agent_runs() to evaluate output variance for EVERY agent."""
    track = _init_tracking(state)
    wf_id = state.get("workflow_id", "")
    ev_dir = state.get("evidence_dir")
    agents = state.get("discovered_agents", [])

    comparisons = {}
    for aid in agents:
        res = evidence_tools.compare_agent_runs(workflow_id=wf_id, agent_id=aid, evidence_dir=ev_dir)
        comparisons[aid] = res

    track["stage_status"]["stage_9_comparison"] = "completed"
    return {**track, "agent_run_comparisons": comparisons}


