def build_optimization_agent_graph() -> Any:
    """
    Build and compile the sequential LangGraph pipeline:
    - 10 MCP evidence tool calling nodes
    - 3 dedicated autonomous LangGraph optimization agents
    """
    graph = StateGraph(OptimizationAgentState)

    # 1. Register the 10 MCP tool calling nodes
    graph.add_node("stage_1_discovery", stage_1_discovery_tool_node)
    graph.add_node("stage_2_overview", stage_2_overview_tool_node)
    graph.add_node("stage_3_graph", stage_3_graph_tool_node)
    graph.add_node("stage_4_profiles", stage_4_profiles_tool_node)
    graph.add_node("stage_5_prompts", stage_5_prompts_tool_node)
    graph.add_node("stage_6_latency", stage_6_latency_tool_node)
    graph.add_node("stage_7_tokens", stage_7_tokens_tool_node)
    graph.add_node("stage_8_cost", stage_8_cost_tool_node)
    graph.add_node("stage_9_comparison", stage_9_comparison_tool_node)
    graph.add_node("stage_10_evidence", stage_10_evidence_tool_node)

    # 2. Register the 3 LangGraph Optimization Agents
    graph.add_node("optimization_discovery_agent", optimization_discovery_agent_node)
    graph.add_node("tradeoff_assessment_agent", tradeoff_assessment_agent_node)
    graph.add_node("report_generation_agent", report_generation_agent_node)

    # 3. Wire strictly sequential execution edges
    graph.add_edge(START, "stage_1_discovery")
    graph.add_edge("stage_1_discovery", "stage_2_overview")
    graph.add_edge("stage_2_overview", "stage_3_graph")
    graph.add_edge("stage_3_graph", "stage_4_profiles")
    graph.add_edge("stage_4_profiles", "stage_5_prompts")
    graph.add_edge("stage_5_prompts", "stage_6_latency")
    graph.add_edge("stage_6_latency", "stage_7_tokens")
    graph.add_edge("stage_7_tokens", "stage_8_cost")
    graph.add_edge("stage_8_cost", "stage_9_comparison")
    graph.add_edge("stage_9_comparison", "stage_10_evidence")

    # Connect MCP evidence tool outputs directly into the 3 LangGraph Agents
    graph.add_edge("stage_10_evidence", "optimization_discovery_agent")
    graph.add_edge("optimization_discovery_agent", "tradeoff_assessment_agent")
    graph.add_edge("tradeoff_assessment_agent", "report_generation_agent")
    graph.add_edge("report_generation_agent", END)

    return graph.compile()
